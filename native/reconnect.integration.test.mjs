import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,readFile,readdir,stat,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fixture} from '../tests/helpers.js';
import {createApp} from '../server.js';
import {createBridge} from './bridge.mjs';

test('native account sign-in reconnects across bridge restart without codes, keeps credentials private, and respects revocation',async t=>{
 const f=await fixture(t),alice=f.actor('alice'),human=f.tx('createAgent',f.actor('alice'),{kind:'human',name:'Returning player',capabilities:'Build',limitations:'Human controlled'});
 f.platform.run('UPDATE agents SET world_id=?,x=32,y=32,z=0,grounded=1 WHERE id=?','frontier:0:0',human.id);
 const app=createApp({platform:f.platform});await new Promise(r=>app.server.listen(0,'127.0.0.1',r));
 t.after(async()=>{await app.stopWorkers();await new Promise(r=>{app.server.close(r);app.server.closeAllConnections()})});
 const dir=await mkdtemp(join(tmpdir(),'native-remember-'));t.after(()=>rm(dir,{recursive:true,force:true}));
 const api=`http://127.0.0.1:${app.server.address().port}`,key='a'.repeat(64);
 let bridge,base,loginToken=f.credentials.alice.token;
 const launch=async()=>{bridge=createBridge({api,modKey:key,sessionDirectory:dir,clock:()=>f.platform.clock(),fetcher:async(url,options)=>{
  if(new URL(url).pathname==='/api/v1/auth/login') return Response.json({token:loginToken});
  return fetch(url,options);
 }});await new Promise(r=>bridge.listen(0,'127.0.0.1',r));base=`http://127.0.0.1:${bridge.address().port}`};
 t.after(()=>bridge?.listening?new Promise(r=>bridge.close(r)):null);
 const post=async(path,body,authorized=true)=>{const r=await fetch(base+path,{method:'POST',headers:{'Content-Type':'application/json',...(authorized?{'X-Nemo-Mod-Key':key}:{})},body:JSON.stringify(body)});return{status:r.status,data:await r.json()}};
 await launch();
 assert.equal((await post('/native/login',{player:'Returning',email:'alice@example.test',password:'not-logged'},false)).status,401);
 const login=await post('/native/login',{player:'Returning',email:'alice@example.test',password:'not-logged'});
 assert.equal(login.status,200,JSON.stringify(login.data));
 assert.equal(login.data.agents[0].id,human.id);
 assert.ok(!JSON.stringify(login.data).includes(f.credentials.alice.token));
 assert.equal((await post('/native/connect',{player:'SomeoneElse',login_id:login.data.login_id,agent_id:human.id})).status,401);
 const login2=await post('/native/login',{player:'Returning',email:'alice@example.test',password:'not-logged'});
 const connected=await post('/native/connect',{player:'Returning',login_id:login2.data.login_id,agent_id:human.id});
 assert.equal(connected.status,200,JSON.stringify(connected.data));
 const oldNonce=connected.data.pair_id;
 assert.equal((await post('/native/state',{player:'Returning',pair_id:oldNonce})).status,200);
 f.advance(21*60000);
 assert.equal((await post('/native/state',{player:'Returning',pair_id:oldNonce})).status,200,'remembered play must not demand a code after twenty minutes');
 const saved=await readFile(join(dir,'remembered.nemoenc'),'utf8');
 assert.ok(!saved.includes(f.credentials.alice.token));assert.ok(!saved.includes('not-logged'));assert.ok(!saved.includes(human.id));
 for(const name of await readdir(dir))assert.equal((await stat(join(dir,name))).mode&0o077,0);
 await new Promise(r=>bridge.close(r));await launch();
 assert.equal((await post('/native/resume',{player:'SomeoneElse'})).status,404);
 assert.equal((await post('/native/resume',{player:'Returning'},false)).status,401);
 const resumed=await post('/native/resume',{player:'Returning'});
 assert.equal(resumed.status,200,JSON.stringify(resumed.data));assert.notEqual(resumed.data.pair_id,oldNonce);
 assert.equal((await post('/native/state',{player:'Returning',pair_id:oldNonce})).status,401);
 assert.equal((await post('/native/state',{player:'Returning',pair_id:resumed.data.pair_id})).status,200);
 f.platform.run("UPDATE agents SET status='paused' WHERE id=?",human.id);
 assert.equal((await post('/native/resume',{player:'Returning'})).status,403);
 f.platform.run("UPDATE agents SET status='active' WHERE id=?",human.id);
 assert.equal((await post('/native/resume',{player:'Returning'})).status,200);
 f.platform.run('UPDATE tokens SET revoked=1 WHERE hash=?',f.actor('alice').credential.hash);
 assert.equal((await post('/native/resume',{player:'Returning'})).status,401);
 assert.equal((await post('/native/resume',{player:'Returning'})).status,404);
 loginToken=f.platform.transaction(()=>f.platform.loginToken(alice.account)).token;
 const fresh=await post('/native/login',{player:'Returning',email:'alice@example.test',password:'not-logged'});
 const again=await post('/native/connect',{player:'Returning',login_id:fresh.data.login_id,agent_id:human.id});
 assert.equal(again.status,200);
 assert.equal((await post('/native/forget',{player:'Returning',pair_id:'wrong'})).status,401);
 assert.equal((await post('/native/forget',{player:'Returning',pair_id:again.data.pair_id})).status,200);
 await new Promise(r=>bridge.close(r));await launch();
 assert.equal((await post('/native/resume',{player:'Returning'})).status,404);
});
